#!/usr/bin/env python3
"""Sync the Sunny site chat from ONE source into every page + the
shared brain file.

The chat used to be hand-copied into 18 HTML files, so every
knowledge-base edit meant an 18-file sweep. Then (2026-10-29) the
brain moved out of the pages entirely: the knowledge base + engine
now ship as ONE external, cacheable file, /chat-brain.js, and each
page carries only the small shell that fetches it on first wake.

Edit the fragments in this folder, then run:

    python3 chat-source/sync-chat.py          # regenerate everything
    python3 chat-source/sync-chat.py --check  # verify, exit 1 on drift

Commit the fragments, the generated chat-brain.js and the
regenerated pages together. Never edit the chat block inside a page
or chat-brain.js directly - the next sync overwrites them, and
--check flags the drift.

Coverage:
- chat-brain.frag  -> chat-brain.js at the repo root (the generated
                      external file; its sha256 prefix is stamped
                      into the shell as the ?v= cache-buster)
- chat-script.frag -> the shell <script> block in every chat page
                      (18 pages). Pages still carrying the legacy
                      inline brain (marker "function answerFor") are
                      migrated: that block is replaced by the shell.
- chat-panel.frag  -> every page with the chat launcher (18 pages)
- chat-style.frag  -> the 17 template pages that carry the standalone
                      "Sunny site chat" <style> block. index.html keeps
                      its chat styles inside its own stylesheets (its
                      CSS is organised differently) and is skipped for
                      the style segment only.
Pages with no chat (champion holding page, onboard, thank-you, the
Google verification file) are left untouched.
"""
import glob
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "chat-source")
BRAIN_PATH = os.path.join(ROOT, "chat-brain.js")
SHELL_MARKER = "sunny-chat-shell"
LEGACY_MARKER = "function answerFor"


def load(name):
    with open(os.path.join(SRC, name), encoding="utf8") as f:
        return f.read()


STYLE_FRAG = load("chat-style.frag")
PANEL_FRAG = load("chat-panel.frag")
SCRIPT_FRAG = load("chat-script.frag")
BRAIN_FRAG = load("chat-brain.frag")

BRAIN_JS = (
    "/* GENERATED by chat-source/sync-chat.py from chat-source/chat-brain.frag.\n"
    "   Do not edit this file directly - edit the fragment and re-run the sync. */\n"
    + BRAIN_FRAG
)
BRAIN_VERSION = hashlib.sha256(BRAIN_JS.encode()).hexdigest()[:10]
# The shell fragment file ends with a newline after </script>; the
# block spliced into (and compared against) each page is exactly
# <script>...</script>, so strip trailing newlines once, here.
SHELL_FRAG = SCRIPT_FRAG.replace("__SUNNY_BRAIN_V__", BRAIN_VERSION).rstrip("\n")


def blocks(html, tag):
    out = []
    for m in re.finditer(r"<%s(?:\s[^>]*)?>" % tag, html):
        end = html.index("</%s>" % tag, m.start())
        out.append((m.start(), end + len(tag) + 3))
    return out


def swap_block(html, tag, marker, frag, page, label, required):
    hits = [(s, e) for (s, e) in blocks(html, tag) if marker in html[s:e]]
    if not hits:
        if required:
            raise SystemExit("ERROR %s: expected %s block not found" % (page, label))
        return html, False
    if len(hits) > 1:
        raise SystemExit("ERROR %s: %d %s blocks found, expected 1" % (page, len(hits), label))
    s, e = hits[0]
    return html[:s] + frag + html[e:], html[s:e] != frag


def swap_script(html, page):
    """Replace the chat script block - the new shell, or the legacy
    inline brain on pre-externalization pages - with the shell."""
    hits = [(s, e) for (s, e) in blocks(html, "script")
            if SHELL_MARKER in html[s:e] or LEGACY_MARKER in html[s:e]]
    if not hits:
        raise SystemExit("ERROR %s: expected chat script block not found" % page)
    if len(hits) > 1:
        raise SystemExit("ERROR %s: %d chat script blocks found, expected 1" % (page, len(hits)))
    s, e = hits[0]
    return html[:s] + SHELL_FRAG + html[e:], html[s:e] != SHELL_FRAG


def swap_panel(html, page):
    a = html.find('<button class="chat-launcher"')
    if a < 0:
        return html, False, False
    if html.find('<button class="chat-launcher"', a + 1) >= 0:
        raise SystemExit("ERROR %s: more than one chat launcher" % page)
    b = html.find("</section>", a)
    if b < 0:
        raise SystemExit("ERROR %s: chat panel </section> not found" % page)
    b += len("</section>")
    return html[:a] + PANEL_FRAG + html[b:], html[a:b] != PANEL_FRAG, True


def synced(html, page):
    changed = []
    html, ch = swap_block(html, "style", "Sunny site chat", STYLE_FRAG, page, "chat style", required=False)
    if ch:
        changed.append("style")
    html, ch, has_panel = swap_panel(html, page)
    if ch:
        changed.append("panel")
    if has_panel:
        html, ch = swap_script(html, page)
        if ch:
            changed.append("script")
        if "FAQ_INDEX" in html or LEGACY_MARKER in html:
            raise SystemExit("ERROR %s: inline chat brain still present after sync" % page)
        if BRAIN_VERSION not in html:
            raise SystemExit("ERROR %s: shell does not reference brain v%s" % (page, BRAIN_VERSION))
    return html, changed, has_panel


def segment_hash(html, tag, marker):
    for (s, e) in blocks(html, tag):
        if marker in html[s:e]:
            return hashlib.md5(html[s:e].encode()).hexdigest()[:8]
    return None


def main():
    check_only = "--check" in sys.argv
    drift = 0

    # The shared brain file itself.
    current_brain = None
    if os.path.exists(BRAIN_PATH):
        with open(BRAIN_PATH, encoding="utf8") as f:
            current_brain = f.read()
    if current_brain != BRAIN_JS:
        drift += 1
        print("%-45s %s" % ("chat-brain.js", "WOULD CHANGE" if check_only else "regenerated"))
        if not check_only:
            with open(BRAIN_PATH, "w", encoding="utf8") as f:
                f.write(BRAIN_JS)
    else:
        print("%-45s already in sync" % "chat-brain.js")
    print("brain version (content hash): %s | brain bytes: %d" % (BRAIN_VERSION, len(BRAIN_JS.encode())))

    pages = sorted(glob.glob(os.path.join(ROOT, "*.html")))
    chat_pages = 0
    for path in pages:
        page = os.path.basename(path)
        with open(path, encoding="utf8") as f:
            html = f.read()
        new_html, changed, has_panel = synced(html, page)
        if not has_panel:
            print("%-45s no chat - untouched" % page)
            continue
        chat_pages += 1
        shell_hash = segment_hash(new_html, "script", SHELL_MARKER)
        if changed:
            drift += 1
            print("%-45s %s (shell %s)" % (page, "WOULD CHANGE: " + ",".join(changed) if check_only else "synced: " + ",".join(changed), shell_hash))
            if not check_only:
                with open(path, "w", encoding="utf8") as f:
                    f.write(new_html)
        else:
            print("%-45s already in sync (shell %s)" % (page, shell_hash))
    print("---")
    print("chat pages: %d | artifacts %s sync: %d" % (chat_pages, "out of" if check_only else "changed by", drift))
    if check_only and drift:
        sys.exit(1)


if __name__ == "__main__":
    main()
